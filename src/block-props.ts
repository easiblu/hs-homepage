/* ══════════════════════════════════════════════════════════════════════════
   Props for the design-system blocks.

   Hand-written, and NOT regenerated by `npm run port` — the generator only
   writes Home.tsx, home-props.ts, home-behavior.ts and sections/*. The blocks
   are wired in by tools/assemble-home.cjs under DS_BLOCKS, which imports the
   constants below.

   Why this file exists
   ────────────────────
   The blocks bundle the marketing video as a default so they work out of the
   box, but a built copy of the package bakes a root-absolute "/assets/x.mp4"
   into its JavaScript and ships the file inside the package. Nothing copies it
   to the consumer's web root, so those URLs 404 here — in dev and in the
   build. This page already serves every one of those clips from public/uploads
   and has done since the canvas port, so it points the blocks at its own
   copies rather than the package's.

   That is also the right way round: an 18MB reel of marketing video is the
   site's asset, not the component library's. Everything else the blocks ship
   — icons, badges, stills — is inlined as a data URI and needs nothing here.
   ══════════════════════════════════════════════════════════════════════════ */
import {
  DEAL_CARDS,
  APP_SHOWCASE_IOS,
  APP_SHOWCASE_DIGITAL,
  type DealCard,
  type AppShowcaseIosPanel,
  type AppShowcaseDigitalPanel,
} from '@heartstampxo/design-system/hs';

/* The same files the canvas sections used, so nothing new is deployed. */
const CLIPS = {
  dealsBanner: 'uploads/banner.mp4',
  deals3d: 'uploads/3D card.mp4',
  phone: 'uploads/iphone0banner.webm',
  phoneFallback: 'uploads/iphone_banner-v1.mp4',
  tablet: 'uploads/digital3d.mp4',
} as const;

/** Deals, with the two clips served from this site. Order matches DEAL_CARDS. */
export const DEALS_CARDS: DealCard[] = DEAL_CARDS.map((card, i) => ({
  ...card,
  video: { ...card.video, src: [CLIPS.dealsBanner, CLIPS.deals3d][i] },
}));

/** The iPhone panel. The WebM carries alpha; Safari gets the MP4 instead. */
export const APP_IOS: AppShowcaseIosPanel = {
  ...APP_SHOWCASE_IOS,
  video: { ...APP_SHOWCASE_IOS.video, src: CLIPS.phone, fallbackSrc: CLIPS.phoneFallback },
};

/** The tablet panel. */
export const APP_DIGITAL: AppShowcaseDigitalPanel = {
  ...APP_SHOWCASE_DIGITAL,
  video: { ...APP_SHOWCASE_DIGITAL.video, src: CLIPS.tablet },
};
